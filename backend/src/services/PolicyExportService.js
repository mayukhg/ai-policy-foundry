import { logger } from '../utils/logger.js';
import { ValidationError } from '../middleware/errorHandler.js';

export class PolicyExportService {
  constructor() {
    // In production, you would use libraries like:
    // - pdfkit or puppeteer for PDF generation
    // - docx for DOCX generation
  }

  /**
   * Export policy as PDF
   * @param {Object} policyData - Policy data to export
   * @returns {Promise<Buffer>} PDF buffer
   */
  async exportToPDF(policyData) {
    try {
      logger.info('Exporting policy to PDF');

      // In a real implementation, you would use a PDF library like pdfkit or puppeteer
      // For now, we'll return a simple text representation
      const pdfContent = this.formatPolicyForPDF(policyData);

      // Convert to buffer (in production, use actual PDF generation)
      const buffer = Buffer.from(pdfContent, 'utf-8');

      return {
        buffer: buffer,
        mimeType: 'application/pdf',
        filename: `${policyData.metadata?.name || 'policy'}.pdf`
      };

    } catch (error) {
      logger.error('PDF export failed:', error);
      throw new ValidationError('Failed to export policy as PDF');
    }
  }

  /**
   * Export policy as DOCX
   * @param {Object} policyData - Policy data to export
   * @returns {Promise<Buffer>} DOCX buffer
   */
  async exportToDOCX(policyData) {
    try {
      logger.info('Exporting policy to DOCX');

      // In a real implementation, you would use the docx library
      // For now, we'll return a simple text representation
      const docxContent = this.formatPolicyForDOCX(policyData);

      // Convert to buffer (in production, use actual DOCX generation)
      const buffer = Buffer.from(docxContent, 'utf-8');

      return {
        buffer: buffer,
        mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
        filename: `${policyData.metadata?.name || 'policy'}.docx`
      };

    } catch (error) {
      logger.error('DOCX export failed:', error);
      throw new ValidationError('Failed to export policy as DOCX');
    }
  }

  /**
   * Format policy for PDF export
   */
  formatPolicyForPDF(policyData) {
    let content = '';

    // Header
    content += `AI POLICY FOUNDRY\n`;
    content += `Generated Security Policy\n`;
    content += `Generated: ${policyData.metadata?.generatedAt || new Date().toISOString()}\n`;
    content += `\n${'='.repeat(60)}\n\n`;

    // Metadata
    if (policyData.metadata) {
      content += `METADATA\n`;
      content += `${'-'.repeat(60)}\n`;
      content += `Service: ${policyData.metadata.service || 'N/A'}\n`;
      content += `Environment: ${policyData.metadata.environment || 'N/A'}\n`;
      content += `Business Unit: ${policyData.metadata.businessUnit || 'N/A'}\n`;
      content += `Compliance: ${policyData.metadata.compliance || 'N/A'}\n`;
      content += `Risk Level: ${policyData.metadata.riskLevel || 'N/A'}\n`;
      
      if (policyData.traceability) {
        content += `\nSource Document: ${policyData.traceability.sourceDocument}\n`;
      }
      content += `\n${'='.repeat(60)}\n\n`;
    }

    // Policy Content
    content += `POLICY CONTENT\n`;
    content += `${'-'.repeat(60)}\n\n`;
    content += policyData.policy || '';

    // Compliance Information
    if (policyData.compliance) {
      content += `\n\n${'='.repeat(60)}\n`;
      content += `COMPLIANCE INFORMATION\n`;
      content += `${'-'.repeat(60)}\n`;
      content += `Framework: ${policyData.compliance.framework || 'N/A'}\n`;
      if (policyData.compliance.controls) {
        content += `Controls: ${Array.isArray(policyData.compliance.controls) ? policyData.compliance.controls.length : 0}\n`;
      }
    }

    // Security Information
    if (policyData.security) {
      content += `\n\n${'='.repeat(60)}\n`;
      content += `SECURITY ASSESSMENT\n`;
      content += `${'-'.repeat(60)}\n`;
      if (policyData.security.riskAssessment) {
        content += `Risk Level: ${policyData.security.riskAssessment.riskLevel || 'N/A'}\n`;
      }
    }

    // Footer
    content += `\n\n${'='.repeat(60)}\n`;
    content += `This policy was generated by AI Policy Foundry\n`;
    content += `For questions or concerns, please contact your security team.\n`;

    return content;
  }

  /**
   * Format policy for DOCX export
   */
  formatPolicyForDOCX(policyData) {
    // Similar to PDF but with DOCX-specific formatting
    return this.formatPolicyForPDF(policyData);
  }

  /**
   * Export policy as plain text
   */
  exportToText(policyData) {
    return policyData.policy || '';
  }

  /**
   * Export policy as OPA/Rego package (executable operational rules)
   */
  exportToRego(policyData) {
    if (policyData?.rego) {
      return policyData.rego;
    }

    const rawName = policyData?.metadata?.name || policyData?.name || 'policy';
    const packageName = `apf.${rawName.replace(/[^a-zA-Z0-9_]/g, '_').toLowerCase()}`;
    const service = policyData?.metadata?.service || policyData?.service || 'cloud';
    const controls = policyData?.compliance?.controls || [];
    const controlComments = Array.isArray(controls)
      ? controls
          .slice(0, 8)
          .map((c) => `# control: ${typeof c === 'string' ? c : c.controlId || c.id || 'unknown'}`)
          .join('\n')
      : '# control: none';

    return `package ${packageName}

# Auto-generated by AI Policy Foundry
# service: ${service}
${controlComments}

default allow = false

# Require encryption at rest and in transit when mentioned in policy text
allow {
  input.encryption.at_rest == true
  input.encryption.in_transit == true
}

deny[msg] {
  not input.encryption.at_rest
  msg := "encryption at rest is required"
}

deny[msg] {
  input.access.public == true
  msg := "public access is blocked by policy"
}
`;
  }

  async exportPolicy(policyData, format = 'text') {
    switch ((format || 'text').toLowerCase()) {
      case 'pdf':
        return this.exportToPDF(policyData);
      case 'docx':
        return this.exportToDOCX(policyData);
      case 'rego':
      case 'opa': {
        const rego = this.exportToRego(policyData);
        return {
          buffer: Buffer.from(rego, 'utf-8'),
          mimeType: 'text/plain',
          filename: `${policyData.metadata?.name || 'policy'}.rego`,
          content: rego
        };
      }
      case 'yaml':
      case 'text':
      default:
        return {
          buffer: Buffer.from(this.exportToText(policyData), 'utf-8'),
          mimeType: 'text/yaml',
          filename: `${policyData.metadata?.name || 'policy'}.yaml`,
          content: this.exportToText(policyData)
        };
    }
  }
}

export default new PolicyExportService();

